#!/usr/bin/env node
'use strict';

// The hand-written formula card content (scripts/data), and the data migration that
// applies it. A migration rather than a script because it runs exactly once, on the
// deploy that also brings the rules these cards were written to, so no live card is
// ever refused by rules it predates. Merging is the approval.
//
//   node scripts/referenceCardContent.js          checks the data, changes nothing
//   node scripts/referenceCardContent.js --write  regenerates the migration file
//
// Rows that move leave version rows both ways, so any card can be put back.

const fs = require('fs');
const path = require('path');
const { REWRITES, DROPS } = require('./data/referenceCardRewrites');
const { DRAFTS } = require('./data/referenceCardDrafts');
const { referenceCardCreateSchema, validateCardRules } = require('../src/schemas/referenceCardSchemas');

const MIGRATION = path.join(__dirname, '..', 'prisma', 'migrations', '20261110000000_reference_card_content', 'migration.sql');

/** A data row as the card columns: a formula's unit and a constant's value share valueUnit. */
const toContent = (card) => ({
    kind: card.kind,
    symbol: card.symbol ?? null,
    name: card.name,
    formulaLatex: card.f ?? null,
    valueUnit: (card.kind === 'constant' ? card.value : card.unit) ?? null,
    description: card.d,
    variables: card.vars ?? [],
    purposeExamTip: card.tip,
    dimensionless: !!card.dim,
});

/** Every reason a card would be refused: the same gate and shape check as the API. */
function problemsWith(card) {
    const content = { ...toContent(card), subject: card.subject ?? 'EE', topic: card.topic ?? 'any' };
    const parsed = referenceCardCreateSchema.safeParse(content);
    const shape = parsed.success ? [] : parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`);
    return [...shape, ...validateCardRules(content)];
}

const allProblems = () => [...REWRITES, ...DRAFTS]
    .map((card) => ({ name: card.name, problems: problemsWith(card) }))
    .filter((row) => row.problems.length > 0);

const q = (value) => (value === null || value === undefined ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`);
const jsonb = (value) => `${q(JSON.stringify(value))}::jsonb`;
const list = (values) => values.map(q).join(', ');
const SNAPSHOT = `to_jsonb(r) - 'id' - 'createdAt' - 'updatedAt' - 'status'`;
const versions = (action, where, createdAt = 'now()') => `INSERT INTO "ReferenceCardVersion" ("id", "cardId", "action", "editor", "snapshot", "createdAt")
SELECT gen_random_uuid()::text, r."id", ${q(action)}, NULL, ${SNAPSHOT}, ${createdAt}
FROM "ReferenceCard" r WHERE ${where};`;

function buildMigrationSql() {
    const rewriteIds = list(REWRITES.map((c) => c.id));
    const dropIds = list(DROPS.map((c) => c.id));
    const draftNames = list(DRAFTS.map((c) => c.name));
    const updates = REWRITES.map((card) => {
        const c = toContent(card);
        return `UPDATE "ReferenceCard" SET "name" = ${q(c.name)}, "symbol" = ${q(c.symbol)}, "formulaLatex" = ${q(c.formulaLatex)}, "valueUnit" = ${q(c.valueUnit)}, "description" = ${q(c.description)}, "variables" = ${jsonb(c.variables)}, "purposeExamTip" = ${q(c.purposeExamTip)}, "dimensionless" = ${c.dimensionless}, "updatedAt" = now()
WHERE "id" = ${q(card.id)} AND "status" = 'LIVE';`;
    });
    const drops = DROPS.map((card) => `UPDATE "ReferenceCard" SET "status" = 'REJECTED', "reviewNote" = ${q(card.why)}, "reviewedAt" = now(), "updatedAt" = now()
WHERE "id" = ${q(card.id)} AND "status" = 'LIVE';`);
    // From the Topic row, so a database without that topic simply gets no card.
    const inserts = DRAFTS.map((card) => {
        const c = toContent(card);
        return `INSERT INTO "ReferenceCard" ("id", "kind", "symbol", "name", "formulaLatex", "valueUnit", "description", "variables", "purposeExamTip", "subject", "topicId", "subtopicTag", "dimensionless", "status", "createdAt", "updatedAt")
SELECT gen_random_uuid()::text, ${q(c.kind)}, ${q(c.symbol)}, ${q(c.name)}, ${q(c.formulaLatex)}, ${q(c.valueUnit)}, ${q(c.description)}, ${jsonb(c.variables)}, ${q(c.purposeExamTip)}, ${q(card.subject)}, t."id", ${q(card.tag)}, ${c.dimensionless}, 'PENDING', now(), now()
FROM "Topic" t WHERE t."name" = ${q(card.topic)} AND t."subject" = ${q(card.subject)}
ON CONFLICT ("kind", "subject", "name") DO NOTHING;`;
    });
    return [
        '-- Generated by scripts/referenceCardContent.js: change the data there and regenerate.',
        '-- The live formula cards rewritten to one standard, two retired, and new cards for',
        '-- the empty topics, waiting in the review queue.',
        '',
        "-- What each card said before, a moment earlier than the edit.",
        versions('EDITED', `r."status" = 'LIVE' AND r."id" IN (${rewriteIds}, ${dropIds})`, "now() - interval '1 second'"),
        '',
        ...updates,
        '',
        ...drops,
        '',
        versions('EDITED', `r."status" = 'LIVE' AND r."id" IN (${rewriteIds})`),
        versions('REJECTED', `r."status" = 'REJECTED' AND r."id" IN (${dropIds})`),
        '',
        ...inserts,
        '',
        versions('SUBMITTED', `r."status" = 'PENDING' AND r."name" IN (${draftNames})`),
        '',
    ].join('\n');
}

if (require.main === module) {
    const problems = allProblems();
    for (const { name, problems: why } of problems) console.error(`  ${name}: ${why.join(', ')}`);
    console.log(`${REWRITES.length} rewrites, ${DROPS.length} retired, ${DRAFTS.length} new, ${problems.length} with problems.`);
    if (problems.length > 0) process.exit(1);
    if (process.argv.includes('--write')) {
        fs.mkdirSync(path.dirname(MIGRATION), { recursive: true });
        fs.writeFileSync(MIGRATION, buildMigrationSql());
        console.log(`Wrote ${path.relative(process.cwd(), MIGRATION)}.`);
    }
}

module.exports = { toContent, problemsWith, allProblems, buildMigrationSql, MIGRATION };
