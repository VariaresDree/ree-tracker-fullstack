/**
 * How many columns a question's options take, from their printed length:
 * short ones share a row, long ones get a line each. Column-major (A and B
 * down the first column, C and D down the second). The limits are measured on
 * the paper's two-column body, where a 4-across option has about 10 mm for its
 * text after the (A) box:
 *   up to 4 options: 4 across if all fit in 6 characters, 2 if in 18, else 1;
 *   5 or 6 options:  3 across if all fit in 10 characters, 2 if in 18, else 1.
 * @param {string[]} options  as stored (math in $...$)
 * @param {number[]} [measured]  lengths to use instead, per option (a formula
 *   printed as its source is longer than its rendering)
 * @returns {{ cols: number, rows: number }}
 */
export function chooseOptionLayout(options, measured = []) {
  const list = Array.isArray(options) ? options : [];
  const n = list.length;
  const longest = list.reduce((m, o, i) => Math.max(m, measured[i] ?? mathToText(stripChoicePrefix(String(o ?? ''))).length), 0);
  let cols = 1;
  if (n <= 4 && longest <= 6) cols = 4;
  else if (n > 4 && longest <= 10) cols = 3;
  else if (longest <= 18) cols = 2;
  cols = Math.max(1, Math.min(cols, n));
  return { cols, rows: Math.max(1, Math.ceil(n / cols)) };
}

/** The set code printed in footers ("K7P2-9QXA-M3TD"), or '' for a draw never saved as a set. */
export const setCodeFor = (printId) => (printId ? formatPrintId(printId) : '');

/**
 * A draw's scannable answer sheet (sheetLayout's answerSheetGeometry), with
 * the header text every renderer prints: the HTML preview, the LaTeX file and
 * the scanner all take their positions from this one call.
 * @param {object} draw  an ExamDraw, maybe with `printId`, `paper` and edited items
 * @param {{ paper?: string, printId?: string, setCode?: string }} [opts]  override the draw's
 */
export function sheetGeometryFor(draw, { paper, printId, setCode } = {}) {
  const id = printId ?? draw?.printId ?? '';
  return answerSheetGeometry({
    optionCounts: (draw?.items || []).map((it) => (Array.isArray(it.options) ? it.options.length : 0)),
    paper: paper || draw?.paper || 'a4',
    printId: id,
    keyVersion: draw?.keyVersion || '',
    meta: {
      title: draw?.plan?.title || '',
      setLabel: draw?.setLabel || '',
      code: draw?.plan?.code || '',
      // An en dash, as LaTeX prints the paper's own "--".
      practiceLine: PRACTICE_LINE.replace(/ -- /g, ' \u2013 '),
      setCode: setCode ?? setCodeFor(id),
    },
  });
}

/**
 * A QR encoder, payload => module matrix ({ size, get(row, col) }), from the
 * qrcode package loaded on demand; null when it can't load (the sheet then
 * prints the payload as text).
 * @returns {Promise<((payload: string) => object|null)|null>}
 */
export async function loadQrEncoder() {
  try {
    const mod = await import('qrcode');
    const create = mod.create || mod.default?.create;
    if (!create) return null;
    return (payload) => {
      try {
        return create(String(payload), { errorCorrectionLevel: 'M' }).modules;
      } catch {
        return null;
      }
    };
  } catch {
    return null;
  }
}

/** The QR module matrix for one payload, or null. */
export async function loadQrModules(payload) {
  const encode = await loadQrEncoder();
  return encode ? encode(payload) : null;
}
