// --- Math to WinAnsi-safe text -----------------------------------------------
// jsPDF's standard Helvetica only speaks WinAnsi (Latin-1), so mathToText
// turned LaTeX and Unicode math into readable Latin-1 text. The LaTeX export
// uses it to measure how long an option prints (chooseOptionLayout).
const SUP = { 1: '\u00B9', 2: '\u00B2', 3: '\u00B3' }; // superscript 1, 2 and 3 exist in Latin-1

// LaTeX command to readable text. Greek is spelled out (board papers do the
